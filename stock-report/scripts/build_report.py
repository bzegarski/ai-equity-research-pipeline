# ---------- main ----------

def main():
    parser = argparse.ArgumentParser(description="Build /stock-report HTML from a research folder.")
    parser.add_argument("ticker")
    parser.add_argument("--base", default=None, help="Override base directory")
    parser.add_argument("--prep", action="store_true", help="Run prep phase only")
    parser.add_argument("--assemble", action="store_true", help="Run assemble phase only")
    parser.add_argument("--rebuild", action="store_true", help="Clear all section drafts before running")
    parser.add_argument("--rebuild-section", type=int, metavar="N",
                        help="Clear one section's draft before running")
    parser.add_argument("--status", action="store_true", help="Show per-section draft status and exit")
    args = parser.parse_args()

    ticker = args.ticker.upper()
    base = Path(args.base) if args.base else Path(f"~/Research/{ticker}")
    base = base.resolve()
    if not base.exists():
        print(f"ERROR: base directory not found: {base}", file=sys.stderr)
        sys.exit(1)

    if args.status:
        statuses = check_drafts(base)
        for s in statuses:
            tag = s["status"].ljust(8)
            extra = f" ({s['words']}w)" if s.get("words") else ""
            print(f"  {s['num']:02d} {tag} {s['title']}{extra}")
        return

    if args.rebuild and args.rebuild_section:
        print("ERROR: --rebuild and --rebuild-section are mutually exclusive.", file=sys.stderr)
        sys.exit(2)
    if args.rebuild:
        deleted = clear_drafts(base)
        print(f"Cleared {len(deleted)} draft(s): {', '.join(deleted) or '(none)'}")
    elif args.rebuild_section:
        deleted = clear_drafts(base, only_section=args.rebuild_section)
        print(f"Cleared section {args.rebuild_section}: {', '.join(deleted) or '(no draft existed)'}")

    do_prep = args.prep or not args.assemble
    do_assemble = args.assemble or not args.prep
    if not (args.prep or args.assemble):
        do_prep = do_assemble = True

    if do_prep:
        print(f"Prep phase for {ticker}...")
        data = prep(base, ticker)
        print_primer_status(data)
        print(f"  XBRL series: {len(data['xbrl_series_present'])}")
        print(f"  Claims indexed: {data['claims_count']}")
        print(f"  report_data.json written to {drafts_dir(base) / 'report_data.json'}")
        statuses = check_drafts(base)
        missing = [s for s in statuses if s["status"] == "missing"]
        if missing:
            missing_list = ", ".join(f"{s['num']:02d}-{s['slug']}" for s in missing)
            print(f"  {len(missing)} section drafts still pending: {missing_list}")

    if do_assemble:
        print(f"Assemble phase for {ticker}...")
        assemble(base, ticker)


if __name__ == "__main__":
    main()
