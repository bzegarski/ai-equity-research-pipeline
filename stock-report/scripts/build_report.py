"""/stock-report build pipeline.

ARCHITECTURE
------------
Python validates inputs, preps deterministic data (XBRL series, memo header, sector
detection, FACT-claim records, chart specs), runs glossary auto-injection on Claude's
drafts, and assembles the final HTML. Python does NOT write prose. Claude writes each
section's prose into `_report_drafts/section_NN_<slug>.md` (per the per-section writing
prompts in SKILL.md). The drafts are persisted across runs.

USAGE
-----
  py build_report.py TICKER --prep                # validate + write report_data.json
  py build_report.py TICKER --assemble            # read drafts + emit final HTML
  py build_report.py TICKER                       # both phases
  py build_report.py TICKER --rebuild             # clear all drafts, then both phases
  py build_report.py TICKER --rebuild-section N   # clear one draft, then both phases
  py build_report.py TICKER --status              # show which section drafts exist

OUTPUTS
-------
  {BASE}/_report_drafts/report_data.json          # deterministic prep output
  {BASE}/_report_drafts/sector_detected.txt       # GICS sector + reason
  {BASE}/_report_drafts/section_NN_<slug>.md      # per-section drafts (Claude writes)
  {BASE}/_report_drafts/glossary_company.json     # per-company glossary (Claude writes)
  {BASE}/{TICKER}_full_report.html                # final assembled report

Stdlib only.
"""
