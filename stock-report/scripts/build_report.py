# ---------- helpers ----------

def read_text(p: Path) -> str:
    if not p.exists():
        return ""
    try:
        return p.read_text(encoding="utf-8")
    except Exception as e:
        return f"[ERROR reading {p}: {e}]"


def validate(base: Path, ticker: str) -> list[str]:
    missing = []
    for rel in REQUIRED_FILES:
        p = base / rel.replace("{TICKER}", ticker)
        if not p.exists():
            missing.append(str(p))
    return missing


# ---------- XBRL ----------

def parse_xbrl_summary(path: Path) -> dict:
    """Parse `xbrl_summary.txt` into {label: [(end_date, value, unit)]}."""
    if not path.exists():
        return {}
    out: dict[str, list[tuple[str, float, str]]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 4:
            continue
        label_concept = parts[0]
        label = label_concept.split("(", 1)[0].strip()
        end = parts[1]
        try:
            val = float(parts[2])
        except (ValueError, TypeError):
            continue
        unit = parts[3] if len(parts) > 3 else ""
        out.setdefault(label, []).append((end, val, unit))
    for k in out:
        out[k] = sorted(out[k], key=lambda x: x[0])
    return out


# ---------- memo header parsing ----------

def parse_memo_header(memo_md: str) -> dict:
    """Extract decision, company, current price (from 'Stock price anchored to' line),
    intrinsic estimate, and key insight body."""
    info = {
        "decision": "",
        "current_price": "",
        "intrinsic": "",
        "key_insight": "",
        "thesis_one_liner": "",
        "company": "",
        "memo_date": "",
    }

    h1 = re.search(r"^#\s+(.+)$", memo_md, flags=re.MULTILINE)
    if h1:
        info["company"] = h1.group(1).strip()
        date_m = re.search(r"(\d{4}-\d{2}-\d{2})", h1.group(1))
        if date_m:
            info["memo_date"] = date_m.group(1)

    # Canonical "Stock price anchored to: $X" line — must win over any later $NNN
    # because Section 1 typically also contains trigger / watch prices that would
    # otherwise be picked up as the current price.
    for line in memo_md.splitlines()[:60]:
        if "stock price anchored" in line.lower():
            p_m = re.search(r"\$([0-9]+(?:\.[0-9]{1,2})?)", line)
            if p_m:
                info["current_price"] = "$" + p_m.group(1)
                break

    decision_section = _section_body(memo_md, r"Section\s+1\b[^#\n]*|DECISION")
    if decision_section:
        d_m = re.search(r"\b(BUY|WATCHLIST|PASS|REJECT|WATCH)\b", decision_section, re.IGNORECASE)
        if d_m:
            info["decision"] = d_m.group(1).upper()
        if not info["current_price"]:
            p_m = re.search(r"\$([0-9]+(?:\.[0-9]{1,2})?)", decision_section)
            if p_m:
                info["current_price"] = "$" + p_m.group(1)
        first_para = decision_section.strip().split("\n\n", 1)[0]
        info["thesis_one_liner"] = first_para

    if not info["decision"]:
        d_m = re.search(
            r"\b(BUY|WATCHLIST|PASS|REJECT)\b",
            "\n".join(memo_md.splitlines()[:80]),
            re.IGNORECASE,
        )
        if d_m:
            info["decision"] = d_m.group(1).upper()

    ki = _section_body(memo_md, r"Section\s+3\b[^#\n]*|KEY\s+INSIGHT")
    if ki:
        info["key_insight"] = ki.strip()

    intrinsic_m = re.search(
        r"intrinsic[^$]*\$([0-9]+(?:\.[0-9]{1,2})?)",
        memo_md,
        re.IGNORECASE,
    )
    if intrinsic_m:
        info["intrinsic"] = "$" + intrinsic_m.group(1)

    return info


def _section_body(md: str, header_pattern: str) -> str:
    """Find a section by partial header match, return its body up to next ##."""
    for m in re.finditer(r"(?m)^##\s+(.+)$", md):
        if re.search(header_pattern, m.group(1), re.IGNORECASE):
            start = m.end()
            next_m = re.search(r"(?m)^##\s+", md[start:])
            end = start + next_m.start() if next_m else len(md)
            return md[start:end].strip()
    return ""


# ---------- GICS classification (authoritative file only) ----------
# The keyword-fingerprint detector that used to live here was deleted because it
# routinely misclassified service companies that deliver via software (Paychex was
# classified as Information Technology when the correct sector is Industrials).
# The replacement is the universal "don't guess - look up" rule: Claude resolves
# the GICS classification at run time via WebFetch on the company's Wikipedia page
# or IR page, falling back to AskUserQuestion if web lookup fails. That logic lives
# in SKILL.md (Step 0 of the orchestration). Python here is a dumb reader of
# raw/gics.txt; if the file is missing, we exit with a clear error pointing back
# to SKILL.md.

def _load_gics(base: Path) -> dict | None:
    """Read GICS classification from `raw/gics.txt` if present.

    Expected format (case-insensitive keys; whitespace-tolerant):
        Sector: Industrials
        Industry: Professional Services
        Sub-Industry: Human Resource & Employment Services

    Sector is required; Industry and Sub-Industry are optional.
    Returns None if the file is missing.
    """
    p = base / "raw" / "gics.txt"
    if not p.exists():
        return None
    out: dict[str, str] = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip().lower().replace(" ", "_").replace("-", "_")
        value = value.strip()
        if not value:
            continue
        if key in {"sector", "industry", "sub_industry", "subindustry", "industry_group"}:
            # Normalize sub-industry key
            if key == "subindustry":
                key = "sub_industry"
            out[key] = value
    if "sector" not in out:
        return None
    return out


def _slug(name: str) -> str:
    """Normalize a GICS name into the file-slug convention used by the primer prompts.
    'Real Estate Management & Development' -> 'Real_Estate_Management_and_Development'."""
    s = name.replace("&", "and")
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_")
    return s


def resolve_classification(base: Path) -> dict | None:
    """Read GICS classification from raw/gics.txt (the only allowed source).

    Returns a dict with sector / industry / sub_industry / source / reason fields,
    or None if raw/gics.txt is missing. The caller is responsible for handling the
    None case - typically by exiting with a clear instruction pointing the reader to
    SKILL.md's Step 0 (look up GICS via WebFetch on Wikipedia or company IR page;
    AskUserQuestion as fallback). The skill never guesses GICS classification."""
    gics = _load_gics(base)
    if gics is None:
        return None
    return {
        "sector": gics.get("sector", ""),
        "industry": gics.get("industry", ""),
        "sub_industry": gics.get("sub_industry", ""),
        "source": "raw/gics.txt",
        "reason": "Loaded from raw/gics.txt (authoritative).",
    }


def primer_paths(classification: dict) -> dict:
    """Compute expected primer file paths and check presence.
    Returns a dict with sector / industry primer paths, statuses, and the prompt-file
    path the user can run if a primer is missing."""
    skill_assets = SKILL_DIR / "assets"
    out: dict = {"sector": {}, "industry": {}}

    sec = classification.get("sector", "")
    if sec and sec not in {"UNKNOWN", "AMBIGUOUS", ""}:
        sec_slug = _slug(sec)
        sec_primer = skill_assets / "sectors" / f"{sec_slug}_primer.md"
        sec_prompt = skill_assets / "sectors" / "_research_prompts" / f"{sec_slug}_primer_prompt.md"
        out["sector"] = {
            "name": sec,
            "primer_path": str(sec_primer),
            "primer_status": "present" if sec_primer.exists() else "missing",
            "research_prompt_path": str(sec_prompt) if sec_prompt.exists() else None,
        }
    else:
        out["sector"] = {
            "name": sec, "primer_path": "", "primer_status": "no_sector_classification",
            "research_prompt_path": None,
        }

    ind = classification.get("industry", "")
    if ind:
        ind_slug = _slug(ind)
        ind_primer = skill_assets / "industries" / f"{ind_slug}_primer.md"
        ind_prompt = skill_assets / "industries" / "_research_prompts" / f"{ind_slug}_primer_prompt.md"
        out["industry"] = {
            "name": ind,
            "primer_path": str(ind_primer),
            "primer_status": "present" if ind_primer.exists() else "missing",
            "research_prompt_path": str(ind_prompt) if ind_prompt.exists() else None,
        }
    else:
        out["industry"] = {
            "name": "", "primer_path": "", "primer_status": "no_industry_classification",
            "research_prompt_path": None,
        }

    return out


# ---------- claim extraction ----------

CLAIM_RE = re.compile(
    r"\[(FACT|INTERPRETATION|HUMAN-VERIFY)\s*\|\s*([^\|\]]+?)\s*(?:\|\s*([^\]]+?))?\]"
)


def extract_claims(files: dict) -> list[dict]:
    """Scan step files for `[FACT|source|confidence]` style tags. Returns structured
    records. Claude can reference these by id when writing prose; the reader never
    sees the raw [FACT|...] chips in the body."""
    records = []
    cid = 0
    for filename, content in files.items():
        if not filename.startswith("steps/"):
            continue
        for line_num, line in enumerate(content.splitlines(), 1):
            for m in CLAIM_RE.finditer(line):
                cid += 1
                records.append({
                    "id": f"c{cid:04d}",
                    "kind": m.group(1),
                    "source": (m.group(2) or "").strip(),
                    "confidence": (m.group(3) or "").strip(),
                    "file": filename,
                    "line": line_num,
                })
    return records


# ---------- chart specs ----------

def build_chart_specs(xbrl: dict) -> list[dict]:
    """Return list of chart specs for the assembler to render. Each spec:
        {kind, id, title, data, ylabel, caption_slot_section}
    The caption_slot_section tells which section's draft is allowed to write the
    one-line takeaway caption; Claude inserts the caption text inline in the draft
    via a `<!-- chart-caption: chart_id="...", text="..." -->` marker."""
    specs = []
    if not xbrl:
        return specs

    rev = xbrl.get("Revenue") or xbrl.get("Revenues")
    if rev:
        specs.append({
            "kind": "line",
            "id": "revenue_5y",
            "title": "Revenue, 5-year",
            "labels": [d[:4] for d, _, _ in rev[-5:]],
            "series": {"Revenue": [v for _, v, _ in rev[-5:]]},
            "ylabel": "USD",
            "caption_slot_section": 4,
        })

    op = xbrl.get("OperatingIncome")
    if rev and op:
        rev_by_year = {d[:4]: v for d, v, _ in rev}
        labels, margins = [], []
        for d, v, _ in op[-5:]:
            yr = d[:4]
            r = rev_by_year.get(yr)
            if r:
                labels.append(yr)
                margins.append(v / r * 100)
        if labels:
            specs.append({
                "kind": "line",
                "id": "op_margin_5y",
                "title": "Operating margin, 5-year (%)",
                "labels": labels,
                "series": {"Op margin %": margins},
                "ylabel": "%",
                "caption_slot_section": 4,
            })

    ocf = xbrl.get("OperatingCashFlow")
    if ocf:
        specs.append({
            "kind": "bar",
            "id": "ocf_5y",
            "title": "Operating cash flow, 5-year",
            "labels": [d[:4] for d, _, _ in ocf[-5:]],
            "values": [v for _, v, _ in ocf[-5:]],
            "ylabel": "USD",
            "caption_slot_section": 4,
        })

    sh = xbrl.get("SharesOutstanding")
    if sh:
        specs.append({
            "kind": "line",
            "id": "shares_5y",
            "title": "Shares outstanding, 5-year",
            "labels": [d[:4] for d, _, _ in sh[-5:]],
            "series": {"Shares": [v for _, v, _ in sh[-5:]]},
            "ylabel": "shares",
            "caption_slot_section": 4,
        })

    debt = xbrl.get("LongTermDebt")
    if debt:
        specs.append({
            "kind": "bar",
            "id": "debt_5y",
            "title": "Long-term debt, 5-year",
            "labels": [d[:4] for d, _, _ in debt[-5:]],
            "values": [v for _, v, _ in debt[-5:]],
            "ylabel": "USD",
            "caption_slot_section": 4,
        })

    return specs


def render_chart(spec: dict) -> str:
    """Render a chart spec into SVG via svg_charts."""
    if spec["kind"] == "line":
        return svg_charts.line_chart(
            spec["title"], spec["labels"], spec["series"], ylabel=spec.get("ylabel", "")
        )
    if spec["kind"] == "bar":
        return svg_charts.bar_chart(
            spec["title"], spec["labels"], spec["values"], ylabel=spec.get("ylabel", "")
        )
    return f'<!-- chart kind {spec["kind"]} not yet supported -->'


# ---------- draft management ----------

def drafts_dir(base: Path) -> Path:
    return base / "_report_drafts"


def section_filename(num: int, slug: str) -> str:
    return f"section_{num:02d}_{slug}.md"


def section_path(base: Path, num: int, slug: str) -> Path:
    return drafts_dir(base) / section_filename(num, slug)


def clear_drafts(base: Path, only_section: int | None = None) -> list[str]:
    """Delete section drafts. Returns list of deleted filenames."""
    deleted = []
    for num, slug, _, kind in SECTIONS:
        if kind != "claude":
            continue
        if only_section is not None and num != only_section:
            continue
        p = section_path(base, num, slug)
        if p.exists():
            p.unlink()
            deleted.append(p.name)
    return deleted


def check_drafts(base: Path) -> list[dict]:
    """Return per-section status."""
    out = []
    for num, slug, title, kind in SECTIONS:
        if kind != "claude":
            out.append({"num": num, "slug": slug, "title": title, "status": "auto"})
            continue
        p = section_path(base, num, slug)
        if p.exists():
            text = p.read_text(encoding="utf-8")
            out.append({
                "num": num, "slug": slug, "title": title,
                "status": "drafted",
                "words": len(text.split()),
                "path": str(p),
            })
        else:
            out.append({
                "num": num, "slug": slug, "title": title,
                "status": "missing",
                "path": str(p),
            })
    return out


# ---------- prep phase ----------

def prep(base: Path, ticker: str) -> dict:
    """Validate inputs, parse data, detect sector, write report_data.json. Returns
    the data dict in addition to writing it to disk."""
    missing = validate(base, ticker)
    if missing:
        print("ERROR: required input files missing:", file=sys.stderr)
        for m in missing:
            print(f"  - {m}", file=sys.stderr)
        print(
            f"\n/stock-research {ticker} must complete first (memo + verification_a).",
            file=sys.stderr,
        )
        sys.exit(1)

    files: dict[str, str] = {}
    for rel in REQUIRED_FILES + OPTIONAL_FILES:
        key = rel.replace("{TICKER}", ticker)
        files[key] = read_text(base / key)

    xbrl = parse_xbrl_summary(base / "raw" / "xbrl_summary.txt")
    memo_info = parse_memo_header(files.get(f"{ticker}_research_memo.md", ""))

    classification = resolve_classification(base)
    if classification is None:
        print("ERROR: raw/gics.txt is missing and the skill never guesses GICS classification.",
              file=sys.stderr)
        print("", file=sys.stderr)
        print("To produce raw/gics.txt:", file=sys.stderr)
        print("  - WebFetch the company's Wikipedia page; the GICS sector and industry are", file=sys.stderr)
        print("    typically in the infobox.", file=sys.stderr)
        print("  - If Wikipedia lacks the info, try the company's investor-relations page.", file=sys.stderr)
        print("  - If still unresolved, ask the user.", file=sys.stderr)
        print("", file=sys.stderr)
        print("Write the result at " + str(base / "raw" / "gics.txt") + " in the format:", file=sys.stderr)
        print("    Sector: <GICS sector>", file=sys.stderr)
        print("    Industry: <GICS industry>", file=sys.stderr)
        print("    Sub-Industry: <GICS sub-industry>", file=sys.stderr)
        print("", file=sys.stderr)
        print("Then re-run /stock-report. See SKILL.md Step 0 for the full orchestration.",
              file=sys.stderr)
        sys.exit(1)
    primers = primer_paths(classification)

    chart_specs = build_chart_specs(xbrl)
    claims = extract_claims(files)

    data = {
        "_meta": {
            "ticker": ticker,
            "build_date": _dt.date.today().isoformat(),
            "skill_dir": str(SKILL_DIR),
            "research_base": str(base),
            "input_file_status": {
                rel.replace("{TICKER}", ticker): bool(files.get(rel.replace("{TICKER}", ticker), "").strip())
                for rel in REQUIRED_FILES + OPTIONAL_FILES
            },
        },
        "memo": memo_info,
        "gics": classification,
        "primers": primers,
        # Legacy field kept so older code paths still resolve; new code reads `gics`/`primers`.
        "sector": {
            "detected": classification["sector"],
            "reason": classification["reason"],
            "primer_path": primers["sector"].get("primer_path", ""),
            "primer_status": primers["sector"].get("primer_status", ""),
        },
        "xbrl_series_present": sorted(xbrl.keys()),
        "chart_specs": chart_specs,
        "claims_count": len(claims),
        "claims": claims,
        "available_inputs": {
            rel.replace("{TICKER}", ticker): str((base / rel.replace("{TICKER}", ticker)).resolve())
            for rel in REQUIRED_FILES + OPTIONAL_FILES
            if (base / rel.replace("{TICKER}", ticker)).exists()
        },
    }

    drafts_dir(base).mkdir(exist_ok=True)
    (drafts_dir(base) / "report_data.json").write_text(
        json.dumps(data, indent=2), encoding="utf-8"
    )
    # Persist the resolved classification for downstream sections / human inspection.
    gics_lines = [f"Sector: {classification['sector']}"]
    if classification.get("industry"):
        gics_lines.append(f"Industry: {classification['industry']}")
    if classification.get("sub_industry"):
        gics_lines.append(f"Sub-Industry: {classification['sub_industry']}")
    gics_lines.append("")
    gics_lines.append(f"Source: {classification['source']}")
    gics_lines.append(f"Note: {classification['reason']}")
    (drafts_dir(base) / "gics_resolved.txt").write_text(
        "\n".join(gics_lines), encoding="utf-8"
    )
    # Legacy file maintained for backward compatibility.
    (drafts_dir(base) / "sector_detected.txt").write_text(
        f"{classification['sector']}\n\n{classification['reason']}\n", encoding="utf-8"
    )

    return data


